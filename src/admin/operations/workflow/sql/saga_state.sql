RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    -- 控制操作必须在 Saga 提交栅栏内进入审计流，避免后继操作先被游标观察。
    INSERT INTO saga_audit_stream_guard (saga_id, generation) VALUES (NEW.saga_id, 1)
    ON CONFLICT (saga_id) DO UPDATE
        SET generation = saga_audit_stream_guard.generation + 1;
    INSERT INTO saga_audit_event
        (saga_id, record_kind, event_identity, event_revision, control_seq, from_state, to_state,
         operation_id, actor, reason, occurred_at)
    VALUES
        (NEW.saga_id, 'control', NEW.operation_id, 'fact', NEW.control_seq, NEW.from_state,
         NEW.to_state, NEW.operation_id, NEW.actor, NEW.reason, NEW.occurred_at)
    ON CONFLICT DO NOTHING;
    RETURN NEW;
END
$$;

