-- 业务作用：在实例与计时器状态变化时记录数据库侧时间，供治理状态观测与诊断使用。
-- 参数说明: 无。
-- 返回：携带数据库当前更新时间的 NEW 行，由原事务继续保存。
CREATE OR REPLACE FUNCTION nasaga_set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = clock_timestamp();
    RETURN NEW;
END
$$;

-- 业务作用：在 attempt 创建时追加不可变审计事件；事实表与事件表任一写入失败都会阻止业务事实提交。
-- 参数说明: 无。
-- 返回：去重后的审计事件与原事实同事务写入并返回 NEW；写入失败则拒绝原事务。
CREATE OR REPLACE FUNCTION nasaga_audit_attempt_insert()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    -- 先递增所属 Saga 的提交栅栏，再分配 identity 序号，后继事件不能越过未提交前驱。
    INSERT INTO saga_audit_stream_guard (saga_id, generation) VALUES (NEW.saga_id, 1)
    ON CONFLICT (saga_id) DO UPDATE
        SET generation = saga_audit_stream_guard.generation + 1;
    INSERT INTO saga_audit_event
        (saga_id, record_kind, event_identity, event_revision, step_name, phase, attempt_no,
         effect_id, command_id, attempt_status, outcome_event_id, occurred_at)
    VALUES
        (NEW.saga_id, 'attempt', concat_ws(chr(31), NEW.step_name, NEW.phase, NEW.attempt_no),
         'started', NEW.step_name, NEW.phase, NEW.attempt_no, NEW.effect_id, NEW.command_id,
         NEW.status, NEW.outcome_event_id, NEW.started_at)
    ON CONFLICT DO NOTHING;
    RETURN NEW;
END
$$;

-- 业务作用：将 attempt 的后续状态变化追加为新事件，避免原地更新越过已发出的审计游标。
-- 参数说明: 无。
-- 返回：去重后的审计事件与原事实同事务写入并返回 NEW；写入失败则拒绝原事务。
CREATE OR REPLACE FUNCTION nasaga_audit_attempt_update()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    -- attempt 原地变化与其它事实共用 Saga 提交栅栏，断线游标不会跳过迟提交事务。
    INSERT INTO saga_audit_stream_guard (saga_id, generation) VALUES (NEW.saga_id, 1)
    ON CONFLICT (saga_id) DO UPDATE
        SET generation = saga_audit_stream_guard.generation + 1;
    INSERT INTO saga_audit_event
        (saga_id, record_kind, event_identity, event_revision, step_name, phase, attempt_no,
         effect_id, command_id, attempt_status, outcome_event_id, occurred_at)
    VALUES
        (NEW.saga_id, 'attempt', concat_ws(chr(31), NEW.step_name, NEW.phase, NEW.attempt_no),
         concat_ws(chr(31), 'status', NEW.status, COALESCE(NEW.outcome_event_id, '')),
         NEW.step_name, NEW.phase, NEW.attempt_no, NEW.effect_id, NEW.command_id, NEW.status,
         NEW.outcome_event_id, COALESCE(NEW.finished_at, clock_timestamp()))
    ON CONFLICT DO NOTHING;
    RETURN NEW;
END
$$;

-- 业务作用：将实例状态迁移按数据库提交顺序追加到统一审计流。
-- 参数说明: 无。
-- 返回：去重后的审计事件与原事实同事务写入并返回 NEW；写入失败则拒绝原事务。
CREATE OR REPLACE FUNCTION nasaga_audit_transition_insert()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    -- 先取得 Saga guard 权威再分配序号，保持事务提交与审计可见顺序一致。
    INSERT INTO saga_audit_stream_guard (saga_id, generation) VALUES (NEW.saga_id, 1)
    ON CONFLICT (saga_id) DO UPDATE
        SET generation = saga_audit_stream_guard.generation + 1;
    INSERT INTO saga_audit_event
        (saga_id, record_kind, event_identity, event_revision, transition_seq, from_state,
         to_state, trigger_kind, trigger_id, definition_version, occurred_at)
    VALUES
        (NEW.saga_id, 'transition', NEW.transition_seq::text, 'fact', NEW.transition_seq,
         NEW.from_state, NEW.to_state, NEW.trigger_kind, NEW.trigger_id, NEW.definition_version,
         NEW.occurred_at)
    ON CONFLICT DO NOTHING;
    RETURN NEW;
END
$$;

-- 业务作用：将控制面状态变化按数据库提交顺序追加到统一审计流。
